import SwiftUI

extension Font {
    
    static func Ubuntu(size: CGFloat) -> Font {
        .custom("Ubuntu-Regular", size: size)
    }
    
    static func UbuntuBold(size: CGFloat) -> Font {
        .custom("Ubuntu-Bold", size: size)
    }
}
